import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split

# file_path = "/content/drive/MyDrive/Datamining/Credit_Score_Clean.csv"
df = pd.read_csv("Credit_Score_Clean.csv")

# Xóa missing
df = df.dropna()

# Reset index
df = df.reset_index(drop=True)

df.head()

label_map = {
    "Good": 1,
    "Poor": 2,
    "Standard": 3
}

df["Credit_Score"] = df["Credit_Score"].map(label_map)

def row_to_image(row, img_size=14):
    row_str = ",".join([str(x) for x in row])

    ascii_vals = [ord(c) for c in row_str]

    total_pixels = img_size * img_size

    ascii_vals = ascii_vals[:total_pixels] + [0] * max(0, total_pixels - len(ascii_vals))

    return np.array(ascii_vals, dtype=np.uint8).reshape(img_size, img_size)

images = []
labels = []

for i in range(len(df)):
    row = df.iloc[i]

    label = int(row["Credit_Score"])
    features = row.drop("Credit_Score")

    img = row_to_image(features, 14)

    images.append(img)
    labels.append(label)

images = np.array(images)
labels = np.array(labels)

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    images, labels,
    test_size=0.3,
    random_state=42,
    stratify=labels
)

X_train = X_train / 255.0
X_test = X_test / 255.0

np.save("/content/drive/MyDrive/Datamining/train_images.npy", X_train)
np.save("/content/drive/MyDrive/Datamining/test_images.npy", X_test)

np.save("/content/drive/MyDrive/Datamining/train_labels.npy", y_train)
np.save("/content/drive/MyDrive/Datamining/test_labels.npy", y_test)

