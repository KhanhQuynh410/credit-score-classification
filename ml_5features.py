import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import confusion_matrix
from sklearn.svm import SVC
from sklearn.neighbors import KNeighborsClassifier
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.naive_bayes import GaussianNB

# 1. NẠP DỮ LIỆU ĐẶC TRƯNG LAI (HYBRID FEATURES) TỪ FILE NPY CỦA BẠN
# =====================================================================
print("--> Bước 1: Đang nạp bộ đặc trưng lai 5 chiều")
# from google.colab import drive
# drive.mount('/content/drive')
data = np.load(
    "features_relief_5.npy",
    allow_pickle=True
).item()

# data = np.load(
#     "/content/drive/MyDrive/Khai thác dữ liệu/features_relief_5.npy",
#     allow_pickle=True
# ).item()

X_train = data["X_train"]
X_test = data["X_test"]
y_train = data["y_train"]
y_test = data["y_test"]

y_train = y_train + 1
y_test = y_test + 1
print(f"   Shape ma trận X_train: {X_train.shape}")
print(f"   Shape ma trận X_test: {X_test.shape}")
print(f"   Nhãn unique: {np.unique(y_train)}")

# 2. CẤU HÌNH CHUẨN CÁC MÔ HÌNH MACHINE LEARNING THEO ĐÚNG BÀI BÁO
# =====================================================================
models = {
    "Linear SVM": SVC(kernel='linear', random_state=42, class_weight='balanced'),
    "Cubic KNN": KNeighborsClassifier(n_neighbors=5, metric='minkowski', p=3), # p=3 tương đương không gian Cubic
    "Linear Discriminant (LDA)": LinearDiscriminantAnalysis(),
    "Gaussian Naive Bayes": GaussianNB()
}

# 3. HÀM TỰ ĐỘNG TÍNH TOÁN BẢNG CHỈ SỐ TOÁN HỌC (Table 4 Style)
# =====================================================================
def compute_table_4_metrics(cm, model_name):
    rows = []
    total_samples = np.sum(cm)
    class_names = ["Good (1)", "Poor (2)", "Standard (3)"]

    for i in range(3):
        TP = cm[i, i]
        FP = np.sum(cm[:, i]) - TP
        FN = np.sum(cm[i, :]) - TP
        TN = total_samples - (TP + FP + FN)

        # Công thức toán phân lớp chuẩn quốc tế
        Se = TP / (TP + FN) if (TP + FN) > 0 else 0
        Sp = TN / (TN + FP) if (TN + FP) > 0 else 0
        Pre = TP / (TP + FP) if (TP + FP) > 0 else 0
        F_scr = (2 * TP) / (2 * TP + FP + FN) if (2 * TP + FP + FN) > 0 else 0
        Acc = (TP + TN) / total_samples

        rows.append({
            "Classifier": model_name,
            "Class": class_names[i],
            "Acc": round(Acc, 4),
            "Se (Sensitivity)": round(Se, 4),
            "Sp (Specificity)": round(Sp, 4),
            "Pre (Precision)": round(Pre, 4),
            "F-scr": round(F_scr, 4),
            "Support": np.sum(cm[i, :])
        })
    return rows

# 4. VÒNG LẶP HUÂN LUYỆN, DỰ ĐOÁN VÀ TRÍCH XUẤT ĐỒ THỊ
# =====================================================================
all_baseline_results = []

print("\n--> Bước 2: Tiến hành huấn luyện và kiểm thử phân lớp hệ thống...")
for name, clf in models.items():
    print(f"\n[XỬ LÝ] Đang chạy bộ phân loại: {name} ...")

    # Huấn luyện mô hình Học máy
    clf.fit(X_train, y_train)

    # Đưa ra dự đoán
    y_pred = clf.predict(X_test)

    # Tính ma trận nhầm lẫn thực tế ứng với nhãn (1, 2, 3)
    cm = confusion_matrix(y_test, y_pred, labels=[1, 2, 3])

    # Tính độ chính xác toàn cục (Overall Accuracy)
    overall_acc = np.sum(np.diag(cm)) / np.sum(cm) * 100
    print(f"   --> Kết quả: Overall Accuracy của {name} đạt: {overall_acc:.2f}%")

    # Thu thập số liệu chi tiết
    all_baseline_results.extend(compute_table_4_metrics(cm, name))

    # Vẽ đồ thị ma trận nhầm lẫn trực quan ra khung hình hiển thị (Fig. 10 Style)
    plt.figure(figsize=(5, 4))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', cbar=False,
                xticklabels=['1', '2', '3'], yticklabels=['1', '2', '3'],
                linewidths=1, linecolor='black', square=True,
                annot_kws={"size": 11, "weight": "bold"})
    plt.title(f"Confusion Matrix - {name}", fontsize=11, fontweight='bold', pad=10)
    plt.xlabel('Predicted Class', fontsize=9)
    plt.ylabel('True Class', fontsize=9)
    plt.tight_layout()

    # Lưu file ảnh vật lý ra thanh bên trái
    plt.savefig(f"fig10_{name.lower().replace(' ', '_').replace('(', '').replace(')', '')}_cm.png", dpi=300)
    plt.show() # Ép in trực tiếp biểu đồ ra khung dưới ô code

# 5. XUẤT BẢNG TỔNG HỢP CHỈ SỐ CUỐI CÙNG (TABLE 4 STYLE)
# =====================================================================
df_baseline_metrics = pd.DataFrame(all_baseline_results)
df_baseline_metrics.to_csv("table4_baseline_classifiers_metrics.csv", index=False)

print("\n" + "="*85)
print("BẢNG TỔNG HỢP CHỈ SỐ THEO TABLE 4 CỦA BÀI BÁO (TRÊN ĐẶC TRƯNG LAI)")
print("="*85)
print(df_baseline_metrics.to_string(index=False))
print("="*85)

